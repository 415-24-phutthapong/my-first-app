import streamlit as st

# 1. แสดงชื่อแอปพลิเคชัน
st.title("🛒 แอปพลิเคชันคำนวณราคาสินค้ารวม VAT 7%")

# 2. สร้างช่องรับข้อมูลตัวเลขราคา
price = st.number_input("กรอกราคาสินค้า (บาท):", value=0.0)

# 3. คำนวณค่า VAT และราคาสุทธิ
vat = price * 0.07
net_price = price - vat

# 4. แสดงผลการคำนวณ
st.header(f"• ภาษีมูลค่าเพิ่ม (VAT 7%): **{vat:.2f}** บาท")
st.header(f"• ราคาสุทธิ: {net_price:.2f} บาท")

# 5. เส้นกั้นและแสดงข้อมูลผู้จัดทำ
st.divider()
st.write("นายพฤฒพงศ์ เนตรยอง เลขที่ 24 ม.4/15")
